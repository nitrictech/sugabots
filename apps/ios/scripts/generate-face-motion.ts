/**
 * Writes `Sugabots/Design/FaceMotion.generated.swift` from how
 * `@sugabots/avatars` brings bots' faces to life, and the mood loops the web
 * app gives them, so the app's faces move by the same numbers as the web's.
 * What each act does with them is copied by hand, in `FaceRig.swift`.
 */
import * as rig from "../../../packages/avatars/src/face-rig.ts";
import { pacingByLiveliness } from "../../../packages/avatars/src/group-pacing.ts";
import { HOP_SECONDS, hopPaths } from "../../../packages/avatars/src/hop.ts";
import * as layers from "../../../packages/avatars/src/layer-motion.ts";
import { defaultLiveliness, livelinessLevels } from "../../../packages/avatars/src/liveliness.ts";
import { OFTEN_REST_SHARE } from "../../../packages/avatars/src/mood-loop.ts";
import {
	botMoods,
	EXCITED_BOUNCE,
	EXCITED_FULL_HOP_CHANCE,
	HAPPY_BOUNCE,
	moods,
} from "../../../packages/avatars/src/moods.ts";
import type { Span } from "../../../packages/avatars/src/random.ts";
import { JUMP_INTERVAL_MS, WATCHING_REACH } from "../../../packages/avatars/src/watching.ts";
import { CREATION_MOODS, WATCHING_MOODS } from "../../../packages/web/src/lib/face-moods.ts";
import type { GeneratedFiles } from "./generated-files.ts";

type Path = layers.Path;
type Keyframes = Extract<Path, { kind: "keyframes" }>;
type SpringPath = Extract<Path, { kind: "spring" }>;

const numbers = (values: readonly number[]) => `[${values.join(", ")}]`;
const span = ({ least, most }: Span) => `Span(least: ${least}, most: ${most})`;
const spring = ({
	stiffness,
	damping,
	restDelta,
	restSpeed,
}: {
	stiffness: number;
	damping: number;
	restDelta?: number;
	restSpeed?: number;
}) =>
	`SpringTuning(stiffness: ${stiffness}, damping: ${damping}${restDelta === undefined ? "" : `, restDelta: ${restDelta}`}${restSpeed === undefined ? "" : `, restSpeed: ${restSpeed}`})`;
/** A named easing as Swift's `Easing`; the app knows only the names the faces use. */
function easing(ease: unknown): string {
	if (typeof ease !== "string")
		throw new Error(`The app's faces take named easings only, not ${String(ease)}`);
	return `.${ease}`;
}
const keyframes = ({ frames, times, ease, seconds }: Keyframes) =>
	`Keyframes(frames: [${frames.map(numbers).join(", ")}], times: ${numbers(times)}, ease: [${ease.map(easing).join(", ")}], seconds: ${seconds})`;

function onlyKeyframes(path: Path | undefined): Keyframes {
	if (path?.kind !== "keyframes") throw new Error("A hop's first path is keyframes");
	return path;
}

function onlySpring(path: Path | undefined): SpringPath {
	if (path?.kind !== "spring") throw new Error("A hop settles with a spring");
	return path;
}

function moodLiteral(mood: (typeof botMoods)[number]): string {
	const { look, gaze, watches, act } = moods[mood];
	const parts = [
		`look: MoodLook(eyesOpen: ${look.eyesOpen}, smile: ${look.smile}, arcsFlat: ${look.arcsFlat}, dots: ${look.dots}, eyesLift: ${look.eyesLift}, headDrop: ${look.headDrop}, headLean: ${look.headLean})`,
		`gaze: Gaze(x: ${gaze?.x ?? 0}, y: ${gaze?.y ?? 0})`,
		`watches: ${watches === true}`,
		`act: ${act ? `MoodAct(pause: ${span(act.pause)}, firstPause: ${span(act.firstPause ?? act.pause)})` : "nil"}`,
	];
	return `Mood(${parts.join(", ")})`;
}

function loopLiteral(spells: typeof WATCHING_MOODS): string {
	const literals = spells.map(
		(spell) =>
			`MoodSpell(mood: .${spell.mood}, weight: ${spell.weight}, seconds: ${span(spell.seconds)})`,
	);
	return `MoodLoop(rest: ${literals[0]}, others: [${literals.slice(1).join(", ")}])`;
}

export function generate(): GeneratedFiles {
	const hop = hopPaths(1);
	const [squash, squashSettle] = hop.squash;
	const [eyesDrop, eyesDropSettle] = hop.eyesDrop;
	/** A constant, typed as Swift can't infer from a whole number: a number or numbers as `Double`s, else Swift `code` of `type`. */
	const constant = (
		doc: string,
		name: string,
		value: number | readonly number[] | { code: string; type: string },
	) => {
		const [type, code] =
			typeof value === "number"
				? ["Double", `${value}`]
				: "code" in value
					? [value.type, value.code]
					: ["[Double]", numbers(value)];
		return [`\t/// ${doc}`, `\tstatic let ${name}: ${type} = ${code}`];
	};
	const lines = [
		"// Generated by apps/ios/scripts/generate-face-motion.ts from @sugabots/avatars and the web app's",
		"// `lib/face-moods.ts`. Do not edit.",
		"",
		"/// How much bot faces move, as someone has chosen, as `Liveliness`.",
		"enum Liveliness: String, CaseIterable {",
		...livelinessLevels.map((level) => `\tcase ${level}`),
		"",
		"\t/// What someone gets before they choose, as `defaultLiveliness`.",
		`\tstatic let chosenByDefault = Liveliness.${defaultLiveliness}`,
		"",
		"\t/// How the faces in a group take turns to move, as `pacingByLiveliness`; none move when off.",
		"\tvar groupPacing: GroupPacing? {",
		"\t\tswitch self {",
		...livelinessLevels.map((level) => {
			if (level === "off") return "\t\tcase .off: nil";
			const pacing = pacingByLiveliness[level];
			return `\t\tcase .${level}: GroupPacing(movingAtOnce: ${pacing.movingAtOnce}, gapSeconds: ${span(pacing.gapSeconds)}, turnSeconds: ${span(pacing.turnSeconds)})`;
		}),
		"\t\t}",
		"\t}",
		"}",
		"",
		"/// The moods a bot can be in, as `botMoods`.",
		"enum BotMood: String, CaseIterable {",
		...botMoods.map((mood) => `\tcase ${mood}`),
		"",
		"\t/// How the mood holds the face and how often it acts, as `moods`.",
		"\tvar mood: Mood {",
		"\t\tswitch self {",
		...botMoods.map((mood) => `\t\tcase .${mood}: ${moodLiteral(mood)}`),
		"\t\t}",
		"\t}",
		"}",
		"",
		"/// The numbers a face moves by, as `face-rig.ts`, `hop.ts`, `layer-motion.ts`, `mood-loop.ts` and `watching.ts` give them.",
		"/// Distances are in the face's 40-unit viewbox unless they say they're percentages of the face.",
		"enum FaceMotion {",
		...constant(
			"The shared clock's ticks, which every change falls on.",
			"tickSeconds",
			layers.TICK_SECONDS,
		),
		...constant(
			"How finely a spring is stepped through to find when it settles.",
			"springSettleStepSeconds",
			layers.SPRING_SETTLE_STEP_MILLISECONDS / 1000,
		),
		...constant(
			"A spring is cut off by this long at the latest.",
			"longestSpringSeconds",
			layers.LONGEST_SPRING_MILLISECONDS / 1000,
		),
		...constant(
			"How far ahead a path is looked at to tell how fast it's moving.",
			"velocitySeconds",
			layers.VELOCITY_SECONDS,
		),
		...constant(
			"How long a repeating path takes to ease to where it starts.",
			"leadInSeconds",
			layers.LEAD_IN_SECONDS,
		),
		"",
		...constant(
			"How far the eyes slide sideways looking all the way.",
			"eyeTravelX",
			rig.EYE_TRAVEL_X,
		),
		...constant(
			"How far the eyes slide up or down looking all the way.",
			"eyeTravelY",
			rig.EYE_TRAVEL_Y,
		),
		...constant("How far the eyes dip as they near the side.", "eyeEdgeDip", rig.EYE_EDGE_DIP),
		...constant(
			"How much narrower the eyes get looking all the way to one side.",
			"eyeForeshortening",
			rig.EYE_FORESHORTENING,
		),
		...constant(
			"How far the head moves sideways after the eyes.",
			"headTravelX",
			rig.HEAD_TRAVEL_X,
		),
		...constant(
			"How far the head moves up or down after the eyes.",
			"headTravelY",
			rig.HEAD_TRAVEL_Y,
		),
		...constant(
			"How far the head tilts, in degrees, looking all the way to one side.",
			"headTiltDegrees",
			rig.HEAD_TILT_DEGREES,
		),
		...constant("How the eyes jump to what they look at.", "eyesSpring", {
			code: spring(rig.EYES_SPRING),
			type: "SpringTuning",
		}),
		...constant("How the head follows the eyes, late, overshooting a little.", "headSpring", {
			code: spring(rig.HEAD_SPRING),
			type: "SpringTuning",
		}),
		...constant("How a mood's pose settles in when it changes.", "moodSpring", {
			code: spring(rig.MOOD_SPRING),
			type: "SpringTuning",
		}),
		...constant("How the eyes' shapes settle into a new mood.", "eyeShapeMoodSpring", {
			code: spring(rig.EYE_SHAPE_MOOD_SPRING),
			type: "SpringTuning",
		}),
		...constant("How far a blink squeezes an eye.", "blinkClosed", rig.BLINK_CLOSED),
		...constant("How long a blink takes.", "blinkSeconds", rig.BLINK.duration),
		...constant("When in a blink the eye is shut and opens again.", "blinkTimes", rig.BLINK.times),
		...constant(
			"The wait between a double blink's two.",
			"blinkTwiceGapSeconds",
			rig.BLINK.repeatDelay,
		),
		...constant(
			"How long after the eyes were last on typing idle glances take over again.",
			"watchingRestSeconds",
			rig.WATCHING_REST_MS / 1000,
		),
		...constant("How far open a sleepy bot's eyes flutter.", "flutterOpen", rig.FLUTTER_OPEN),
		...constant("How long a flutter takes.", "flutterSeconds", rig.FLUTTER_SECONDS),
		...constant("When in a flutter the eyes are widest.", "flutterTimes", rig.FLUTTER_TIMES),
		...constant("How a flutter opens and shuts.", "flutterEase", {
			code: `[${rig.FLUTTER_EASE.map(easing).join(", ")}]`,
			type: "[Easing]",
		}),
		...constant(
			"How far a wiggle leans the head to each side, in degrees.",
			"wiggleDegrees",
			rig.WIGGLE_DEGREES,
		),
		...constant("How far a wiggle moves the head to each side.", "wiggleShift", rig.WIGGLE_SHIFT),
		...constant("How long one wiggle there and back takes.", "wiggleSeconds", rig.WIGGLE_SECONDS),
		...constant(
			"Side to side and back: centre, right, centre, left, centre.",
			"wiggleSides",
			rig.WIGGLE_SIDES,
		),
		...constant("When in a wiggle the head is at each side.", "wiggleTimes", rig.WIGGLE_TIMES),
		...constant(
			"How high a thinking dot rises against its own height.",
			"dotRiseShare",
			rig.DOT_RISE_SHARE,
		),
		...constant(
			"How long one rise of the thinking dots takes.",
			"dotCycleSeconds",
			rig.DOT_CYCLE_SECONDS,
		),
		...constant(
			"How long each thinking dot rises after the one before.",
			"dotStaggerSeconds",
			rig.DOT_STAGGER_SECONDS,
		),
		...constant("How bright a risen thinking dot is.", "dotBrightest", rig.DOT_BRIGHTEST),
		...constant(
			"A resting thinking dot's rise and brightness.",
			"dotRest",
			layers.layerKinds.dot.rest,
		),
		...constant(
			"When in each rise a dot is at its height and back down.",
			"dotRiseTimes",
			rig.DOT_RISE_TIMES,
		),
		...constant(
			"How far the mood has turned to thinking as the outer dots start and finish growing.",
			"outerDotsGrow",
			rig.OUTER_DOTS_GROW,
		),
		...constant(
			"How far the mood has turned to thinking as the middle dot starts and finishes growing.",
			"middleDotGrows",
			rig.MIDDLE_DOT_GROWS,
		),
		...constant(
			"How quickly a wiggle or the thinking dots ease back to rest.",
			"stillingSeconds",
			rig.STILLING_SECONDS,
		),
		"",
		...constant("How long a hop takes from crouch to landing.", "hopSeconds", HOP_SECONDS),
		...constant("A full hop's rise, in percentages of the face.", "hopRise", {
			code: keyframes(onlyKeyframes(hop.rise)),
			type: "Keyframes",
		}),
		...constant("A full hop's squash and stretch, as width and height.", "hopSquash", {
			code: keyframes(onlyKeyframes(squash)),
			type: "Keyframes",
		}),
		...constant("How the head springs back to its size after landing.", "hopSquashSettle", {
			code: spring(onlySpring(squashSettle)),
			type: "SpringTuning",
		}),
		...constant(
			"How far the eyes trail the head through a full hop, in percentages of the face.",
			"hopEyesDrop",
			{ code: keyframes(onlyKeyframes(eyesDrop)), type: "Keyframes" },
		),
		...constant("How the eyes spring back to their place after landing.", "hopEyesDropSettle", {
			code: spring(onlySpring(eyesDropSettle)),
			type: "SpringTuning",
		}),
		"",
		...constant(
			"How big a happy bot's little bounces are, against a full hop.",
			"happyBounce",
			HAPPY_BOUNCE,
		),
		...constant(
			"How big an excited bot's bounces on the spot are, against a full hop.",
			"excitedBounce",
			{ code: span(EXCITED_BOUNCE), type: "Span" },
		),
		...constant(
			"How often an excited bot's bounce is a full hop instead.",
			"excitedFullHopChance",
			EXCITED_FULL_HOP_CHANCE,
		),
		...constant(
			"How much shorter a mood loop's resting spell is when faces move often.",
			"oftenRestShare",
			OFTEN_REST_SHARE,
		),
		...constant(
			"How many face-widths away typing must be for the eyes to look all the way to it.",
			"watchingReach",
			WATCHING_REACH,
		),
		...constant(
			"The least time between the eyes' jumps to typing.",
			"watchingJumpSeconds",
			JUMP_INTERVAL_MS / 1000,
		),
		"",
		...constant(
			"How a bot's face carries itself while someone writes to it, as `WATCHING_MOODS`.",
			"watchingMoods",
			{ code: loopLiteral(WATCHING_MOODS), type: "MoodLoop" },
		),
		...constant("How the bot being made carries itself, as `CREATION_MOODS`.", "creationMoods", {
			code: loopLiteral(CREATION_MOODS),
			type: "MoodLoop",
		}),
		"}",
		"",
	];
	return { files: new Map([["Sugabots/Design/FaceMotion.generated.swift", lines.join("\n")]]) };
}
