/** `MAX_EVERY_DAYS` as a Swift name: `maxEveryDays`. */
const swiftName = (constant: string) =>
	constant.toLowerCase().replace(/_([a-z])/g, (_, letter: string) => letter.toUpperCase());

function swiftScalar(value: number | string): string {
	if (typeof value === "string") return JSON.stringify(value);
	if (!Number.isInteger(value)) throw new Error(`${value} is not a whole number`);
	// Thousands set apart, as Swift writes them: `20_000`.
	return Math.abs(value) < 10_000
		? String(value)
		: value.toLocaleString("en-US").replaceAll(",", "_");
}

/** A value as Swift: a number or text as it is, named values as a tuple. */
function swiftValue(value: LimitValue): string {
	if (typeof value !== "object") return swiftScalar(value);
	const fields = Object.entries(value).map(([name, field]) => `${name}: ${swiftScalar(field)}`);
	return `(${fields.join(", ")})`;
}

export function swift(values: Readonly<Record<string, LimitValue>>): string {
	const declarations = Object.entries(values).flatMap(([name, value]) => [
		`\t/// \`${name}\` in \`@sugabots/contracts\`.`,
		`\tstatic let ${swiftName(name)} = ${swiftValue(value)}`,
	]);
	return [
		"// Generated by apps/ios/scripts/generate-limits.ts from @sugabots/contracts. Do not edit.",
		"import Foundation",
		"",
		"/// The limits the API checks and the apps' screens keep to, as the web's.",
		"enum Limits {",
		...declarations,
		"}",
		"",
	].join("\n");
}

export function generate(): GeneratedFiles {
	return { files: new Map([["Sugabots/API/Limits.generated.swift", swift(limits)]]) };
}
