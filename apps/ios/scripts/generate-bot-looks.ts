/**
 * Writes `Sugabots/Design/BotLooks.generated.swift` from `@sugabots/avatars`
 * and the web app's pod palette, so the app draws bots and pods from the same
 * geometry and colours as the web.
 */
import { botColors } from "../../../packages/avatars/src/bot-colors.ts";
import { type FaceMark, faceMarks } from "../../../packages/avatars/src/face-marks.ts";
import { headShape } from "../../../packages/avatars/src/head-shapes.ts";
import { agentColors, agentFaces, agentShapes } from "../../../packages/contracts/src/agents.ts";
import { podColors } from "../../../packages/contracts/src/pods.ts";
import type { GeneratedFiles } from "./generated-files.ts";

/** The hue of each pod colour, as `podPalettes` in the web app's `PodTile` gives it. */
const podHues: Record<(typeof podColors)[number], number> = {
	green: 148,
	blue: 255,
	plum: 340,
	amber: 78,
	teal: 192,
	purple: 298,
	rose: 18,
	orange: 50,
};

const swiftString = (value: string) => JSON.stringify(value);
const hex = (value: string) => `Color(hex: ${swiftString(value)})`;
const themed = ({ light, dark }: { light: string; dark: string }) =>
	`ThemedColor(light: ${hex(light)}, dark: ${hex(dark)})`;

function headLiteral(shape: (typeof agentShapes)[number]): string {
	const head = headShape(shape);
	const parts = head.parts.map((part) =>
		part.kind === "circle"
			? `.circle(cx: ${part.cx}, cy: ${part.cy}, r: ${part.r})`
			: `.path(${swiftString(part.d)})`,
	);
	const { x, y, scale } = head.eyes;
	return `HeadShape(parts: [${parts.join(", ")}], eyes: EyePlacement(x: ${x}, y: ${y}, scale: ${scale}))`;
}

function marksLiteral(face: (typeof agentFaces)[number]): string {
	return `[${faceMarks(face).map(markLiteral).join(", ")}]`;
}

function markLiteral(mark: FaceMark): string {
	switch (mark.shape) {
		case "circle":
			return `.circle(cx: ${mark.cx}, cy: ${mark.cy}, r: ${mark.r})`;
		case "rect":
			return `.rect(x: ${mark.x}, y: ${mark.y}, width: ${mark.width}, height: ${mark.height}, rx: ${mark.rx})`;
		case "stroke":
			return `.stroke(${swiftString(mark.d)}, width: ${mark.strokeWidth})`;
	}
}

/** An `oklch()` colour as sRGB hex, so Swift needs no colour space of its own for it. */
function oklchHex(lightness: number, chroma: number, hue: number): string {
	const radians = (hue * Math.PI) / 180;
	const a = chroma * Math.cos(radians);
	const b = chroma * Math.sin(radians);
	const l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3;
	const m = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3;
	const s = (lightness - 0.0894841775 * a - 1.291485548 * b) ** 3;
	const linear = [
		4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
		-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
		-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
	];
	return `#${linear
		.map((channel) => {
			const clamped = Math.min(1, Math.max(0, channel));
			const encoded = clamped <= 0.0031308 ? 12.92 * clamped : 1.055 * clamped ** (1 / 2.4) - 0.055;
			return Math.round(encoded * 255)
				.toString(16)
				.padStart(2, "0");
		})
		.join("")}`;
}

export function generate(): GeneratedFiles {
	const lines = [
		"// Generated by apps/ios/scripts/generate-bot-looks.ts from @sugabots/avatars. Do not edit.",
		"",
		"import SwiftUI",
		"",
		"enum BotLooks {",
		"\tstatic let palettes: [String: BotPalette] = [",
		...agentColors.map((color) => {
			const palette = botColors[color];
			return `\t\t${swiftString(color)}: BotPalette(face: ${hex(palette.face)}, eyes: ${hex(palette.eyes)}, tint: ${themed(palette.tint)}, text: ${themed(palette.text)}, mono: ${themed(palette.mono)}),`;
		}),
		"\t]",
		"",
		"\tstatic let heads: [String: HeadShape] = [",
		...agentShapes.map((shape) => `\t\t${swiftString(shape)}: ${headLiteral(shape)},`),
		"\t]",
		"",
		"\tstatic let faces: [String: [FaceMark]] = [",
		...agentFaces.map((face) => `\t\t${swiftString(face)}: ${marksLiteral(face)},`),
		"\t]",
		"",
		"\t/// Each pod colour's tile tint and swatch, as `podPalettes` in the web app's `PodTile` draws them.",
		"\tstatic let pods: [String: PodPalette] = [",
		...podColors.map((color) => {
			const hue = podHues[color];
			return `\t\t${swiftString(color)}: PodPalette(tile: ThemedColor(light: ${hex(oklchHex(0.9, 0.05, hue))}, dark: ${hex(oklchHex(0.33, 0.07, hue))}), swatch: ${hex(oklchHex(0.7, 0.16, hue))}),`;
		}),
		"\t]",
		"}",
		"",
	];
	return { files: new Map([["Sugabots/Design/BotLooks.generated.swift", lines.join("\n")]]) };
}
