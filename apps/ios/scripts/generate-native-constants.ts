/**
 * Writes `Sugabots/Design/NativeConstants.generated.swift` from
 * `apps/native-constants.json`: the values where the native apps
 * deliberately differ from the web, which `apps/NATIVE.md` gives the reasons
 * for, so each native app takes the same ones.
 */
import { readFileSync } from "node:fs";
import type { GeneratedFiles } from "./generated-files.ts";

const source = new URL("../../native-constants.json", import.meta.url);

/** One constant: a length in points, a count, some text, or a list of texts. */
type NativeConstant = { about: string } & (
	| { value: number; unit: "points" | "count" }
	| { value: string }
	| { value: string[] }
);

/** The constants by name, read from the JSON file and checked to be one of the kinds above. */
export function nativeConstants(): Record<string, NativeConstant> {
	const parsed: Record<string, NativeConstant> = JSON.parse(readFileSync(source, "utf8"));
	for (const [name, constant] of Object.entries(parsed)) {
		const { value } = constant;
		const valid =
			typeof constant.about === "string" &&
			(typeof value === "string" ||
				(Array.isArray(value) && value.every((item) => typeof item === "string")) ||
				(typeof value === "number" &&
					"unit" in constant &&
					["points", "count"].includes(constant.unit)));
		if (!valid) throw new Error(`${name} in native-constants.json is not a known kind of constant`);
	}
	return parsed;
}

const string = (text: string) => JSON.stringify(text);

function swiftDeclaration(name: string, constant: NativeConstant): string {
	const { value } = constant;
	if (typeof value === "string") return `static let ${name} = ${string(value)}`;
	if (Array.isArray(value)) return `static let ${name} = [${value.map(string).join(", ")}]`;
	const type = "unit" in constant && constant.unit === "points" ? "CGFloat" : "Int";
	return `static let ${name}: ${type} = ${value}`;
}

export function swift(constants: Record<string, NativeConstant>): string {
	const declarations = Object.entries(constants).flatMap(([name, constant]) => [
		`\t/// ${constant.about}`,
		`\t${swiftDeclaration(name, constant)}`,
	]);
	return [
		"// Generated by apps/ios/scripts/generate-native-constants.ts from apps/native-constants.json. Do not edit.",
		"import CoreGraphics",
		"",
		"/// Where the native apps deliberately differ from the web; `apps/NATIVE.md` says why.",
		"enum NativeConstants {",
		...declarations,
		"}",
		"",
	].join("\n");
}

export function generate(): GeneratedFiles {
	return {
		files: new Map([["Sugabots/Design/NativeConstants.generated.swift", swift(nativeConstants())]]),
	};
}
