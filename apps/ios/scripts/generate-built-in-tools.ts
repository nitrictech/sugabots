/**
 * Writes `Sugabots/Conversation/BuiltInTools.generated.swift` from the
 * product's own tools in `@sugabots/contracts`, so a step names a built-in
 * tool as the web does.
 */
import { builtInToolCatalog } from "../../../packages/contracts/src/built-in-tools.ts";
import type { GeneratedFiles } from "./generated-files.ts";

export function generate(): GeneratedFiles {
	const swift = `// Generated by apps/ios/scripts/generate-built-in-tools.ts from @sugabots/contracts. Do not edit.

extension ToolNames {
	/// The product's own tools' names, by key, as \`builtInToolCatalog\` names them.
	static let builtIn: [String: String] = [
${builtInToolCatalog.map((tool) => `\t\t${JSON.stringify(tool.key)}: ${JSON.stringify(tool.name)},`).join("\n")}
	]
}
`;
	return { files: new Map([["Sugabots/Conversation/BuiltInTools.generated.swift", swift]]) };
}
