/**
 * Writes `Sugabots/Conversation/BuiltInTools.generated.swift` from the
 * product's own tools in `@sugabots/contracts`, so a step names a built-in
 * tool as the web does, and a bot's settings list them as the web's do.
 */
import {
	type BuiltInToolEntry,
	builtInToolCatalog,
} from "../../../packages/contracts/src/built-in-tools.ts";
import type { GeneratedFiles } from "./generated-files.ts";

export function swift(catalog: readonly BuiltInToolEntry[]): string {
	const string = JSON.stringify;
	return `// Generated by apps/ios/scripts/generate-built-in-tools.ts from @sugabots/contracts. Do not edit.

extension ToolNames {
	/// The product's own tools' names, by key, as \`builtInToolCatalog\` names them.
	static let builtIn: [String: String] = [
${catalog.map((tool) => `\t\t${string(tool.key)}: ${string(tool.name)},`).join("\n")}
	]
}

/// One of the bot's own tools, as \`builtInToolCatalog\` lists them.
struct BuiltInTool {
	let key: String
	let name: String
	/// What the tool does, in one plain sentence.
	let description: String
	/// Whether it reaches the web, so works only while the workspace allows that.
	let usesWeb: Bool

	static let catalog = [
${catalog.map((tool) => `\t\tBuiltInTool(key: ${string(tool.key)}, name: ${string(tool.name)}, description: ${string(tool.description)}, usesWeb: ${tool.usesWeb}),`).join("\n")}
	]
}
`;
}

export function generate(): GeneratedFiles {
	return {
		files: new Map([
			["Sugabots/Conversation/BuiltInTools.generated.swift", swift(builtInToolCatalog)],
		]),
	};
}
