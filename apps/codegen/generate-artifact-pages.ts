/**
 * Writes `Sugabots/Artifacts/ArtifactPages.generated.swift` from how the web
 * frames a bot-made page: the content policy and the theme's stylesheet in
 * `@sugabots/contracts/artifact-pages`, the height report, the frame's height
 * limits, and the tokens the page is given, with the values
 * `packages/web/src/app.css` gives each colour in light and dark and each font;
 * and from `packages/web/src/lib/artifact-kind-catalog.ts`, what each kind of
 * artifact is called and what Download saves it as.
 */
import { readFileSync } from "node:fs";
import {
	PAGE_CONTENT_POLICY,
	pageHeightObserver,
	pageThemeCss,
} from "../../packages/contracts/src/artifact-pages.ts";
import {
	ARTIFACT_KIND_FILES,
	ARTIFACT_KIND_LABELS,
} from "../../packages/web/src/lib/artifact-kind-catalog.ts";
import { FIT_HEIGHT_PX, FRAME_TOKENS } from "../../packages/web/src/lib/page-frame.ts";
import { colourTokens, type Rgba } from "./generate-palette.ts";
import type { GeneratedFiles } from "./generated-files.ts";

/** The script message handler a page in the app's web view reports its height to. */
const HEIGHT_MESSAGE_HANDLER = "pageHeight";

/** Placeholders for the stylesheet's two values, swapped for Swift's interpolations. */
const COLOR_SCHEME_SLOT = "@@colorScheme@@";
const TOKENS_SLOT = "@@tokens@@";

const stylesheet = new URL("../../packages/web/src/app.css", import.meta.url);

/** The artifact kind an app shows a kind it doesn't know as. */
const KIND_FOR_UNKNOWN = "document";

/**
 * Each of `FRAME_TOKENS` with its value in light and dark: a colour as
 * `app.css` resolves it on `:root`, or a font as `app.css` declares it, the
 * same in both.
 */
function frameTokens(): { name: string; light: string; dark: string }[] {
	const colours = colourTokens();
	const css = readFileSync(stylesheet, "utf8");
	return FRAME_TOKENS.map((token) => {
		const colour = colours.get(token.slice("--".length));
		if (colour)
			return { name: token, light: cssColour(colour.light), dark: cssColour(colour.dark) };
		const font = token.startsWith("--font-") && declaredValue(css, token);
		if (font) return { name: token, light: font, dark: font };
		throw new Error(`${token} is neither a colour on :root nor a font app.css declares`);
	});
}

/** The value of the first declaration of `property` in `css`, if it has one. */
function declaredValue(css: string, property: string): string | undefined {
	return css.match(new RegExp(`${property}:\\s*([^;]+);`))?.[1]?.trim();
}

const byte = (channel: number) => Math.round(channel * 255);

function cssColour({ red, green, blue, alpha }: Rgba): string {
	if (alpha !== 1) return `rgba(${byte(red)}, ${byte(green)}, ${byte(blue)}, ${alpha})`;
	return `#${[red, green, blue].map((channel) => byte(channel).toString(16).padStart(2, "0")).join("")}`;
}

/** Everything the generated file holds, as data, for each app's copy to be written from. */
export function pageFrame() {
	return {
		contentPolicy: PAGE_CONTENT_POLICY,
		heightMessageHandler: HEIGHT_MESSAGE_HANDLER,
		heightReport: pageHeightObserver(
			(height) => `window.webkit.messageHandlers.${HEIGHT_MESSAGE_HANDLER}.postMessage(${height})`,
		),
		fitHeight: FIT_HEIGHT_PX,
		tokens: frameTokens(),
		themeCss: pageThemeCss({ colorScheme: COLOR_SCHEME_SLOT, tokens: TOKENS_SLOT }),
		kinds: Object.keys(ARTIFACT_KIND_LABELS).map((kind) => ({
			kind,
			label: ARTIFACT_KIND_LABELS[kind as keyof typeof ARTIFACT_KIND_LABELS],
			fileExtension: ARTIFACT_KIND_FILES[kind as keyof typeof ARTIFACT_KIND_FILES].extension,
		})),
	};
}

const string = (text: string) => JSON.stringify(text);

/**
 * A Swift `switch self` over `ArtifactKind` returning `caseValue` of each kind's
 * entry, and for a kind the app doesn't know, `KIND_FOR_UNKNOWN`'s.
 */
function switchOverKinds(
	kinds: ReturnType<typeof pageFrame>["kinds"],
	caseValue: (entry: ReturnType<typeof pageFrame>["kinds"][number]) => string,
): string {
	const cases = kinds.map(
		(entry) =>
			`\t\tcase .${entry.kind}${entry.kind === KIND_FOR_UNKNOWN ? ", .unknown" : ""}: ${caseValue(entry)}`,
	);
	return `switch self {\n${cases.join("\n")}\n\t\t}`;
}

export function swift(frame: ReturnType<typeof pageFrame>): string {
	const themeCss = string(frame.themeCss)
		.replace(COLOR_SCHEME_SLOT, "\\(colorScheme)")
		.replace(TOKENS_SLOT, "\\(tokens)");
	return `// Generated by apps/codegen/generate-artifact-pages.ts from @sugabots/contracts, packages/web/src/lib/page-frame.ts and packages/web/src/app.css. Do not edit.
import CoreGraphics

/// How a bot-made page is framed, as the web frames it.
enum PageFrame {
	/// \`PAGE_CONTENT_POLICY\`: inline code and styles, scripts from one CDN, and data the page embeds.
	static let contentPolicy = ${string(frame.contentPolicy)}

	/// The script message handler \`heightReport\` posts the page's height to.
	static let heightMessageHandler = ${string(frame.heightMessageHandler)}

	/// Reports the page's height whenever it changes, as \`PAGE_HEIGHT_REPORT\` does to a parent frame.
	static let heightReport = ${string(frame.heightReport)}

	/// \`FIT_HEIGHT_PX\`: how tall a frame fitted to its page may be before it is clipped.
	static let fitHeight = (min: CGFloat(${frame.fitHeight.min}), max: CGFloat(${frame.fitHeight.max}))

	/// \`FRAME_TOKENS\`, with the values \`app.css\` gives each in light and dark.
	static let tokens: [(name: String, light: String, dark: String)] = [
${frame.tokens.map(({ name, light, dark }) => `\t\t(${string(name)}, ${string(light)}, ${string(dark)}),`).join("\n")}
	]

	/// \`pageThemeCss\`: the stylesheet a page gets its theme from, on a transparent ground.
	static func themeCss(colorScheme: String, tokens: String) -> String {
		${themeCss}
	}
}

/// What each kind of artifact is called and saved as, as \`ARTIFACT_KIND_LABELS\`
/// and \`ARTIFACT_KIND_FILES\`; a kind this app doesn't know is shown as a ${KIND_FOR_UNKNOWN}.
extension ArtifactKind {
	/// What it is called beside its title.
	var label: String {
		${switchOverKinds(frame.kinds, (entry) => string(entry.label))}
	}

	/// What Download ends its file with.
	var fileExtension: String {
		${switchOverKinds(frame.kinds, (entry) => string(entry.fileExtension))}
	}
}
`;
}

export function generate(): GeneratedFiles {
	return {
		files: new Map([["Sugabots/Artifacts/ArtifactPages.generated.swift", swift(pageFrame())]]),
	};
}
