/**
 * Writes `Sugabots/Design/Lucide.generated.swift` with every Lucide icon the
 * web app imports, as SVG path data, so the app draws the same icons as the
 * web rather than SF Symbols.
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { GeneratedFiles } from "./generated-files.ts";

const webSource = fileURLToPath(new URL("../../packages/web/src", import.meta.url));
const lucide = join(
	dirname(createRequire(join(webSource, "..", "package.json")).resolve("lucide-react")),
	"..",
	"esm",
);

type Attributes = Record<string, string | number>;
type IconNode = [string, Attributes][];

/** Every source file under `directory`, leaving out stories and tests. */
function sourceFiles(directory: string): string[] {
	return readdirSync(directory).flatMap((name) => {
		const path = join(directory, name);
		if (statSync(path).isDirectory()) return sourceFiles(path);
		return /\.tsx?$/.test(name) && !/\.(stories|test)\.tsx?$/.test(name) ? [path] : [];
	});
}

/** The names imported from `lucide-react`, leaving out its types. */
function importedIcons(): Set<string> {
	const names = new Set<string>();
	for (const file of sourceFiles(webSource)) {
		for (const match of readFileSync(file, "utf8").matchAll(
			/import\s*\{([^}]+)\}\s*from\s*"lucide-react"/g,
		)) {
			for (const part of match[1]?.split(",") ?? []) {
				const name = part
					.trim()
					.replace(/^type\s+/, "")
					.replace(/\s+as\s+\w+$/, "");
				if (name && !part.trim().startsWith("type ") && !name.startsWith("Lucide")) names.add(name);
			}
		}
	}
	return names;
}

/** Each export of `lucide-react` with the file that defines it. */
function iconFiles(): Map<string, string> {
	const files = new Map<string, string>();
	const index = readFileSync(join(lucide, "lucide-react.mjs"), "utf8");
	for (const match of index.matchAll(/export \{([^}]+)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g)) {
		for (const part of match[1]?.split(",") ?? []) {
			const name = part.trim().replace(/^default as /, "");
			if (match[2]) files.set(name, match[2]);
		}
	}
	return files;
}

function iconNode(file: string): IconNode {
	const source = readFileSync(join(lucide, "icons", `${file}.mjs`), "utf8");
	const literal = source.match(/node: (\[[\s\S]*?\]),\n\s*aliases|node: (\[[\s\S]*?\])\n\};/);
	const text = literal?.[1] ?? literal?.[2];
	if (!text) throw new Error(`No icon node in ${file}`);
	return Function(`return ${text}`)() as IconNode;
}

const number = (value: string | number | undefined) => Number(value ?? 0);

/** One element of an icon as path data. */
function pathData([tag, attributes]: [string, Attributes]): string {
	switch (tag) {
		case "path":
			return String(attributes.d);
		case "line":
			return `M${attributes.x1} ${attributes.y1}L${attributes.x2} ${attributes.y2}`;
		case "polyline":
		case "polygon": {
			const points = String(attributes.points)
				.trim()
				.split(/[\s,]+/);
			const pairs = [];
			for (let i = 0; i < points.length; i += 2) pairs.push(`${points[i]} ${points[i + 1]}`);
			return `M${pairs.join("L")}${tag === "polygon" ? "Z" : ""}`;
		}
		case "circle":
		case "ellipse": {
			const cx = number(attributes.cx);
			const cy = number(attributes.cy);
			const rx = number(attributes.rx ?? attributes.r);
			const ry = number(attributes.ry ?? attributes.r);
			return `M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}Z`;
		}
		case "rect": {
			const x = number(attributes.x);
			const y = number(attributes.y);
			const width = number(attributes.width);
			const height = number(attributes.height);
			const rx = Math.min(number(attributes.rx ?? attributes.ry), width / 2);
			const ry = Math.min(number(attributes.ry ?? attributes.rx), height / 2);
			if (rx === 0 && ry === 0) return `M${x} ${y}h${width}v${height}h${-width}Z`;
			return [
				`M${x + rx} ${y}`,
				`H${x + width - rx}`,
				`A${rx} ${ry} 0 0 1 ${x + width} ${y + ry}`,
				`V${y + height - ry}`,
				`A${rx} ${ry} 0 0 1 ${x + width - rx} ${y + height}`,
				`H${x + rx}`,
				`A${rx} ${ry} 0 0 1 ${x} ${y + height - ry}`,
				`V${y + ry}`,
				`A${rx} ${ry} 0 0 1 ${x + rx} ${y}Z`,
			].join("");
		}
		default:
			throw new Error(`Unknown icon element ${tag}`);
	}
}

/** `ChevronRight` as a Swift case: `chevronRight`. */
const caseName = (name: string) => name[0]?.toLowerCase() + name.slice(1);

export function generate(): GeneratedFiles {
	const files = iconFiles();
	const icons = [...importedIcons()]
		.filter((name) => files.has(name))
		.sort()
		.map((name) => ({ name, paths: iconNode(files.get(name) as string).map(pathData) }));

	const swift = `// Generated by apps/codegen/generate-lucide-icons.ts from lucide-react. Do not edit.

/// Every Lucide icon the web app uses, by its name there.
enum Lucide: String, CaseIterable {
${icons.map(({ name }) => `\tcase ${caseName(name)}`).join("\n")}

	/// Its strokes, as path data on a 24-point square.
	var paths: [String] {
		switch self {
${icons
	.map(
		({ name, paths }) =>
			`\t\tcase .${caseName(name)}: [${paths.map((path) => JSON.stringify(path)).join(", ")}]`,
	)
	.join("\n")}
		}
	}
}
`;
	return { files: new Map([["Sugabots/Design/Lucide.generated.swift", swift]]) };
}
