/**
 * Writes two lists the web keeps private to its `lib` modules, read from their
 * source, so the app's copies of those modules' rules use the same:
 *
 * - `Sugabots/Conversation/FileLook.generated.swift`: the extensions of the
 *   files drawn as a sheet, `SHEET_EXTENSIONS` in `lib/file-looks.ts`.
 * - `Sugabots/Settings/TimeZoneRegions.generated.swift`: the regions time
 *   zones are listed under, `NAMED_REGIONS` and `OTHER_REGION` in
 *   `lib/time-zones.ts`.
 *
 * Those modules import values from `@sugabots/contracts`, which Node can't load
 * from here, so each list is found in its module's text, and a list that is
 * no longer written as expected stops the generator rather than going missing.
 */
import { readFileSync } from "node:fs";
import type { GeneratedFiles } from "./generated-files.ts";

const fileLooks = new URL("../../packages/web/src/lib/file-looks.ts", import.meta.url);
const timeZones = new URL("../../packages/web/src/lib/time-zones.ts", import.meta.url);

/** The text `pattern` captures in `source`, which must hold it. */
function captured(source: URL, pattern: RegExp): string {
	const match = readFileSync(source, "utf8").match(pattern)?.[1];
	if (match === undefined) throw new Error(`${pattern} matches nothing in ${source.pathname}`);
	return match;
}

/** The string literals in `text`, in order. */
function stringLiterals(text: string): string[] {
	return [...text.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(
		([literal]) => JSON.parse(literal) as string,
	);
}

function sheetExtensions(): string[] {
	const extensions = stringLiterals(
		captured(fileLooks, /const SHEET_EXTENSIONS = new Set\(\[([^\]]*)\]\)/),
	);
	if (extensions.length === 0) throw new Error("SHEET_EXTENSIONS lists no extensions");
	return extensions;
}

/** The named regions, each the first part of its zones' names and what the region is called. */
function namedRegions(): { prefix: string; name: string }[] {
	const list = captured(timeZones, /const NAMED_REGIONS[^=]*= \[\n([\s\S]*?)\n\];/);
	const regions = [...list.matchAll(/^\s*\[("[^"]*"), ("[^"]*")\],$/gm)].map(
		([, prefix, name]) => ({
			prefix: JSON.parse(prefix ?? "") as string,
			name: JSON.parse(name ?? "") as string,
		}),
	);
	const lines = list.split("\n").filter((line) => line.trim() !== "");
	if (regions.length === 0 || regions.length !== lines.length) {
		throw new Error("NAMED_REGIONS isn't a list of [prefix, name] pairs, one to a line");
	}
	return regions;
}

function otherRegion(): string {
	return JSON.parse(captured(timeZones, /const OTHER_REGION = ("[^"]*");/)) as string;
}

const string = (text: string) => JSON.stringify(text);

function fileLookSwift(extensions: string[]): string {
	return `// Generated by apps/codegen/generate-file-and-zone-lists.ts from packages/web/src/lib/file-looks.ts. Do not edit.

extension FileLook {
	/// The extensions of files drawn as a sheet, as \`SHEET_EXTENSIONS\`.
	static let sheetExtensions: Set<String> = [${extensions.map(string).join(", ")}]
}
`;
}

function timeZoneRegionsSwift(regions: { prefix: string; name: string }[], other: string): string {
	return `// Generated by apps/codegen/generate-file-and-zone-lists.ts from packages/web/src/lib/time-zones.ts. Do not edit.

extension TimeZoneRegion {
	/// The regions a zone's first part names, as people call them, in the order they are listed, as \`NAMED_REGIONS\`.
	static let named: [(prefix: String, name: String)] = [
${regions.map((region) => `\t\t(${string(region.prefix)}, ${string(region.name)}),`).join("\n")}
	]

	/// What the region of every zone outside the named ones is called, as \`OTHER_REGION\`.
	static let otherName = ${string(other)}
}
`;
}

export function generate(): GeneratedFiles {
	return {
		files: new Map([
			["Sugabots/Conversation/FileLook.generated.swift", fileLookSwift(sheetExtensions())],
			[
				"Sugabots/Settings/TimeZoneRegions.generated.swift",
				timeZoneRegionsSwift(namedRegions(), otherRegion()),
			],
		]),
	};
}
