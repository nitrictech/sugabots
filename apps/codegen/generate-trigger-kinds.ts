/**
 * Writes `Sugabots/Routines/TriggerKinds.generated.swift` from the words in
 * `packages/web/src/lib/routine-trigger-words.ts`: each kind of trigger a
 * routine may have, as the list of kinds offers it, and what each webhook
 * source's sender must do to be let in.
 */
import {
	TRIGGER_KINDS,
	WEBHOOK_SOURCE_NOTES,
} from "../../packages/web/src/lib/routine-trigger-words.ts";
import type { GeneratedFiles } from "./generated-files.ts";

const string = (text: string) => JSON.stringify(text);

/** A snake_case value as the camelCase name of its Swift case, as the API's generated enums name them. */
const swiftCase = (value: string) =>
	value.replace(/_([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());

/** A `switch self` over every kind, each kind's case returning `caseValue` of it. */
function switchOverKinds(caseValue: (choice: (typeof TRIGGER_KINDS)[number]) => string): string {
	return TRIGGER_KINDS.map(
		(choice) => `\t\tcase .${swiftCase(choice.kind)}: ${caseValue(choice)}`,
	).join("\n");
}

export function swift(): string {
	return `// Generated by apps/codegen/generate-trigger-kinds.ts from packages/web/src/lib/routine-trigger-words.ts. Do not edit.

/// A kind of trigger a routine may have, as \`TRIGGER_KINDS\` lists them: Sugabots' own first.
enum TriggerKind: String, CaseIterable, Identifiable {
${TRIGGER_KINDS.map((choice) => `\tcase ${swiftCase(choice.kind)}${swiftCase(choice.kind) === choice.kind ? "" : ` = ${string(choice.kind)}`}`).join("\n")}

	var id: String { rawValue }

	var label: String {
		switch self {
${switchOverKinds((choice) => string(choice.label))}
		}
	}

	/// What it runs on, in the line under its label.
	var sub: String {
		switch self {
${switchOverKinds((choice) => string(choice.sub))}
		}
	}

	/// The kind of connection the bot's pod needs for it, for an integration's trigger.
	var connection: ConnectionKind? {
		switch self {
${switchOverKinds((choice) => (choice.connection ? `.${swiftCase(choice.connection)}` : "nil"))}
		}
	}
}

extension WebhookAuthChoice {
	/// What a caller must do to be let in, for each source that signs its own way, as \`WEBHOOK_SOURCE_NOTES\`.
	static let sourceNotes: [String: String] = [
${Object.entries(WEBHOOK_SOURCE_NOTES)
	.map(([source, note]) => `\t\t${string(source)}: ${string(note)},`)
	.join("\n")}
	]
}
`;
}

export function generate(): GeneratedFiles {
	return { files: new Map([["Sugabots/Routines/TriggerKinds.generated.swift", swift()]]) };
}
