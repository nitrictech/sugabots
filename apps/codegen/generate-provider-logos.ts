/**
 * Copies `@sugabots/provider-logos`' SVGs, untouched as that package asks,
 * into the app's asset catalog, a dark version as the dark appearance where
 * there is one, and writes `Sugabots/Design/ProviderLogos.generated.swift`
 * mapping each provider preset to its logo and scale.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { providerModelCapabilityCatalog } from "../../packages/contracts/src/model-providers.ts";
import {
	OPENAI_COMPATIBLE_PATH,
	providerCatalog,
	seededPresets,
	signInServiceNames,
} from "../../packages/contracts/src/provider-catalog.ts";
import type { GeneratedFiles } from "./generated-files.ts";

const logos = fileURLToPath(new URL("../../packages/provider-logos/", import.meta.url));
const catalog = "Sugabots/Assets.xcassets/ProviderLogos/";
const source = readFileSync(`${logos}src/provider-logos.ts`, "utf8");

// `import openaiDark from "../logos/openai-dark.svg";`: each import's name and file.
const files = new Map(
	[...source.matchAll(/import (\w+) from "\.\.\/logos\/([\w-]+)\.svg";/g)].map((match) => [
		match[1],
		match[2],
	]),
);

/** Each preset's light and dark logo and its scale, read from `providerLogos`. */
const entries = [...source.matchAll(/\n\t([\w]+): \{([\s\S]*?)\n\t\},/g)].map((match) => {
	const body = match[2] ?? "";
	const light = /light: (\w+)/.exec(body)?.[1];
	const dark = /dark: (\w+)/.exec(body)?.[1];
	const scale = /scale: "scale-(\d+)"/.exec(body)?.[1];
	if (!light || !files.has(light)) throw new Error(`No light logo for ${match[1]}`);
	return {
		preset: match[1] as string,
		light: files.get(light) as string,
		dark: dark ? files.get(dark) : undefined,
		scale: scale ? Number(scale) / 100 : 1,
	};
});

/** The asset catalog: one image set per light logo, with its dark version where it has one. */
function catalogFiles(): Map<string, string> {
	const files = new Map([
		[
			`${catalog}Contents.json`,
			JSON.stringify(
				{
					info: { author: "xcode", version: 1 },
					// What Xcode writes for a folder whose images are named without it.
					properties: { "provides-namespace": false },
				},
				null,
				2,
			),
		],
	]);
	const logo = (name: string) => readFileSync(`${logos}logos/${name}.svg`, "utf8");
	const sets = new Map(entries.map((entry) => [entry.light, entry.dark]));
	for (const [light, dark] of sets) {
		const set = `${catalog}${light}.imageset/`;
		files.set(`${set}${light}.svg`, logo(light));
		const images: object[] = [{ filename: `${light}.svg`, idiom: "universal" }];
		if (dark) {
			files.set(`${set}${dark}.svg`, logo(dark));
			images.push({
				appearances: [{ appearance: "luminosity", value: "dark" }],
				filename: `${dark}.svg`,
				idiom: "universal",
			});
		}
		files.set(
			`${set}Contents.json`,
			JSON.stringify(
				{
					images,
					info: { author: "xcode", version: 1 },
					properties: { "preserves-vector-representation": true },
				},
				null,
				2,
			),
		);
	}
	return files;
}

const swift = `// Generated by apps/codegen/generate-provider-logos.ts from @sugabots/provider-logos. Do not edit.
import CoreGraphics

/// Each provider preset's logo in the asset catalog, and how much it's scaled
/// up to even out the padding its owner built into the file.
enum ProviderLogos {
	static let assets: [String: (image: String, scale: CGFloat)] = [
${entries.map((entry) => `\t\t${JSON.stringify(entry.preset)}: (${JSON.stringify(entry.light)}, ${entry.scale}),`).join("\n")}
	]
}

/// A provider in the catalog, as \`providerCatalog\` lists it.
struct ProviderPreset: Hashable, Identifiable {
	let id: String
	let name: String
	let baseUrl: String
	/// \`remote\` or \`local\`: on somebody else's servers, or on your own machine.
	let hosting: String
	/// \`api-key\`, \`optional\` or \`sign-in\`.
	let credential: String
	/// The service a \`sign-in\` preset signs in with: \`chatgpt\` or \`xai\`.
	let signIn: String?
	let hint: String

	static let catalog: [ProviderPreset] = [
${providerCatalog
	.map(
		(preset) =>
			`\t\tProviderPreset(id: ${JSON.stringify(preset.id)}, name: ${JSON.stringify(preset.name)}, baseUrl: ${JSON.stringify(preset.baseUrl)}, hosting: ${JSON.stringify(preset.hosting)}, credential: ${JSON.stringify(preset.credential)}, signIn: ${"signIn" in preset ? JSON.stringify(preset.signIn) : "nil"}, hint: ${JSON.stringify(preset.hint)}),`,
	)
	.join("\n")}
	]

	/// The providers every workspace starts with, which can't be deleted, only signed out and switched off.
	static let seeded: Set<String> = [${seededPresets.map((id) => JSON.stringify(id)).join(", ")}]

	/// Each sign-in service's name, as \`signInServiceNames\`.
	static let signInServiceNames: [String: String] = [${Object.entries(signInServiceNames)
		.map(([id, name]) => `${JSON.stringify(id)}: ${JSON.stringify(name)}`)
		.join(", ")}]

	/// The path an OpenAI-compatible server answers under, which a bare address is given.
	static let openAICompatiblePath = ${JSON.stringify(OPENAI_COMPATIBLE_PATH)}

	static func named(_ id: String?) -> ProviderPreset? {
		id.flatMap { id in catalog.first { $0.id == id } }
	}
}

/// What a model can do, as \`providerModelCapabilityCatalog\` lists it.
struct ModelCapability: Hashable {
	let key: String
	let name: String
	let description: String

	static let catalog: [ModelCapability] = [
${providerModelCapabilityCatalog
	.map(
		(entry) =>
			`\t\tModelCapability(key: ${JSON.stringify(entry.key)}, name: ${JSON.stringify(entry.name)}, description: ${JSON.stringify(entry.description)}),`,
	)
	.join("\n")}
	]
}
`;

export function generate(): GeneratedFiles {
	const files = catalogFiles();
	files.set("Sugabots/Design/ProviderLogos.generated.swift", swift);
	return { files, folder: catalog };
}
