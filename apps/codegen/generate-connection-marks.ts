/**
 * Writes `Sugabots/Design/ConnectionMarks.generated.swift` from the web app's
 * `ui/connection-mark.tsx` and the connection catalog in `@sugabots/contracts`,
 * so the app draws a connection's mark with the same glyph and tint as the
 * web.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { connectionCatalog } from "../../packages/contracts/src/connections.ts";
import type { GeneratedFiles } from "./generated-files.ts";

const source = readFileSync(
	fileURLToPath(new URL("../../packages/web/src/ui/connection-mark.tsx", import.meta.url)),
	"utf8",
);

/** The object literal assigned to `const name` in the web source. */
function literal<T>(name: string): T {
	const start = source.indexOf(`const ${name}`);
	const open = source.indexOf("= {", start) + 2;
	const close = source.indexOf("\n};", open) + 2;
	if (start < 0 || close < 2) throw new Error(`No ${name} in connection-mark.tsx`);
	return Function(`return ${source.slice(open, close)}`)() as T;
}

interface Glyph {
	hex: string;
	d: string;
}

interface ColourPath {
	d: string;
	fill?: string;
	stroke?: string;
	strokeWidth?: number;
	strokeLinecap?: string;
}

interface ColourMark {
	viewBox: string;
	transform?: string;
	hex?: string;
	paths: ColourPath[];
}

const marks = literal<Record<string, Glyph>>("marks");
const colourMarks = literal<Record<string, ColourMark>>("colourMarks");
const darkBrands = [
	...(/const darkBrands = new Set\(\[([^\]]*)\]\)/.exec(source)?.[1] ?? "").matchAll(/"([^"]+)"/g),
].map((match) => match[1]);

// `color-mix(in oklab, <hex> 14%, var(--panel))`, worked out for each theme's panel.
const PANEL = { light: "#ffffff", dark: "#111113" };
const BRAND_SHARE = 0.14;

const toLinear = (c: number) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const fromLinear = (c: number) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);

function oklab(hex: string): [number, number, number] {
	const [r, g, b] = [1, 3, 5].map((i) => toLinear(Number.parseInt(hex.slice(i, i + 2), 16) / 255));
	const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
	const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
	const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
	return [
		0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
		1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
		0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
	];
}

function hexOf([L, a, b]: [number, number, number]): string {
	const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
	const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
	const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
	const rgb = [
		4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
		-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
		-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
	];
	return `#${rgb
		.map((c) =>
			Math.round(Math.min(1, Math.max(0, fromLinear(c))) * 255)
				.toString(16)
				.padStart(2, "0"),
		)
		.join("")}`;
}

function tint(brand: string, panel: string): string {
	const [x, y] = [oklab(brand), oklab(panel)];
	return hexOf(
		[0, 1, 2].map((i) => x[i] * BRAND_SHARE + y[i] * (1 - BRAND_SHARE)) as [number, number, number],
	);
}

const swiftString = (text: string) => JSON.stringify(text);

/** A path's paint: a literal colour, or the theme token a `var(--…)` names. */
function paint(value: string | undefined): string {
	if (value === undefined || value === "none") return "nil";
	const token = /^var\(--([a-z-]+)\)$/.exec(value)?.[1];
	if (token) return `.token(.${token.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())})`;
	return `.hex(${swiftString(value)})`;
}

function themedTint(hex: string): string {
	return `ThemedColor(light: Color(hex: ${swiftString(tint(hex, PANEL.light))}), dark: Color(hex: ${swiftString(tint(hex, PANEL.dark))}))`;
}

export function generate(): GeneratedFiles {
	const swift = `// Generated by apps/codegen/generate-connection-marks.ts from the web app's
// ui/connection-mark.tsx and @sugabots/contracts. Do not edit.
import SwiftUI

extension ConnectionMark {
	/// One-colour glyphs on a 24-point square, with the tint behind them.
	static let glyphs: [String: Glyph] = [
${Object.entries(marks)
	.map(
		([id, { hex, d }]) =>
			`\t\t${swiftString(id)}: Glyph(color: Color(hex: ${swiftString(hex)}), tint: ${themedTint(hex)}, path: ${swiftString(d)}),`,
	)
	.join("\n")}
	]

	/// Marks drawn in their own colours, on a tint of their brand or on the panel.
	static let colourGlyphs: [String: ColourGlyph] = [
${Object.entries(colourMarks)
	.map(([id, mark]) => {
		const box = mark.viewBox.split(/\s+/).map(Number);
		const paths = mark.paths
			.map(
				(path) =>
					`ColourGlyph.Part(path: ${swiftString(path.d)}, fill: ${paint(path.fill)}, stroke: ${paint(path.stroke)}, strokeWidth: ${path.strokeWidth ?? 0}, roundCap: ${path.strokeLinecap === "round"})`,
			)
			.join(", ");
		return `\t\t${swiftString(id)}: ColourGlyph(size: ${box[2]}, tint: ${mark.hex ? themedTint(mark.hex) : "nil"}, parts: [${paths}]),`;
	})
	.join("\n")}
	]

	/// Brands drawn in the foreground colour, being too dark to read on a dark panel.
	static let darkBrands: Set<String> = [${darkBrands.map(swiftString).join(", ")}]
}

/// An app in the connection catalog, as \`connectionCatalog\` lists it.
struct ConnectionPreset: Hashable, Identifiable {
	let id: String
	let name: String
	let description: String
	let url: String

	static let catalog: [ConnectionPreset] = [
${connectionCatalog
	.map(
		(preset) =>
			`\t\tConnectionPreset(id: ${swiftString(preset.id)}, name: ${swiftString(preset.name)}, description: ${swiftString(preset.description)}, url: ${swiftString(preset.url)}),`,
	)
	.join("\n")}
	]
}
`;
	return { files: new Map([["Sugabots/Design/ConnectionMarks.generated.swift", swift]]) };
}
